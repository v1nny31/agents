import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Skills live in .agents/skills/ so every agent can share them, but Claude Code
// only discovers project skills in .claude/skills/ and has no setting to change
// that, so each skill gets a link there. The links are generated and ignored
// rather than committed: Windows junctions hold an absolute path, and git
// follows them as ordinary folders, which would commit a second copy of every
// skill. Only linked names are ignored, not the whole folder, because other
// tools (e.g. Trail-Code) keep real, committed skills in .claude/skills/ too.
const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SOURCE_DIR = path.join(ROOT, ".agents", "skills");
const LINK_DIR = path.join(ROOT, ".claude", "skills");
const IGNORE_PATH = path.join(LINK_DIR, ".gitignore");

/**
 * Lists the skills available to link.
 *
 * @returns {string[]} Names of the folders in .agents/skills/ that hold a SKILL.md.
 * @throws {Error} If .agents/skills/ does not exist.
 */
function listSkillNames() {
  if (!fs.existsSync(SOURCE_DIR)) {
    throw new Error(`${SOURCE_DIR} does not exist. Copy .agents/skills/ into this project first.`);
  }
  return fs
    .readdirSync(SOURCE_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => fs.existsSync(path.join(SOURCE_DIR, name, "SKILL.md")));
}

/**
 * Removes links whose skill no longer exists. Real folders and links that still
 * resolve are left alone, since they may belong to another tool.
 *
 * @returns {void}
 */
function removeDanglingLinks() {
  for (const name of fs.readdirSync(LINK_DIR)) {
    const linkPath = path.join(LINK_DIR, name);
    if (fs.lstatSync(linkPath).isSymbolicLink() && !fs.existsSync(linkPath)) {
      fs.unlinkSync(linkPath);
    }
  }
}

/**
 * Creates or refreshes the link for one skill. An existing link is always
 * replaced, because one copied from another checkout points back at that checkout.
 *
 * @param {string} name Name of the skill folder in .agents/skills/.
 * @returns {void}
 * @throws {Error} If a real folder or file already exists at the link's path.
 */
function linkSkill(name) {
  const linkPath = path.join(LINK_DIR, name);
  const existing = fs.lstatSync(linkPath, { throwIfNoEntry: false });
  if (existing && !existing.isSymbolicLink()) {
    throw new Error(
      `${linkPath} is a real folder or file, not a link. Move it into .agents/skills/ or delete it, then rerun.`
    );
  }
  if (existing) {
    fs.unlinkSync(linkPath);
  }
  // "junction" needs no admin rights on Windows; other platforms ignore it and
  // create a normal relative symlink.
  fs.symlinkSync(path.relative(LINK_DIR, path.join(SOURCE_DIR, name)), linkPath, "junction");
}

/**
 * Links every skill into .claude/skills/ and ignores those links in git.
 *
 * @returns {void}
 */
function main() {
  const names = listSkillNames();
  fs.mkdirSync(LINK_DIR, { recursive: true });
  removeDanglingLinks();
  names.forEach(linkSkill);
  const ignoreLines = names.map((name) => `/${name}`);
  fs.writeFileSync(
    IGNORE_PATH,
    ["# Generated by .agents/link-claude-skills.mjs", ...ignoreLines, ""].join("\n")
  );
  console.log(`Linked ${names.length} skill(s) into ${LINK_DIR}: ${names.join(", ")}`);
}

try {
  main();
} catch (error) {
  console.error(`[link-claude-skills] ${error.message}`);
  process.exitCode = 1;
}
